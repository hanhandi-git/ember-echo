function tokenize(nameEn) {
  return String(nameEn)
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/[:·]/g, " ")
    .toLowerCase()
    .split(/[\s\-/,]+/)
    .filter((w) => w && w !== "the" && w !== "a" && w !== "an" && w !== "of" && w !== "art");
}

function slugTokens(fxPath) {
  const slug = fxPath.split("/")[1] ?? "";
  return slug.split("-").filter(Boolean);
}

function compose(words, dict, lang) {
  const parts = words.map((w) => dict[w]);
  if (parts.every(Boolean)) return lang === "zh" ? parts.join("") : parts.join("·");
  const known = parts.filter(Boolean);
  if (known.length >= Math.max(2, Math.ceil(words.length * 0.6))) {
    return lang === "zh" ? known.join("") : known.join("·");
  }
  return null;
}

function translateGeneric(nameEn, fxPath, lang) {
  const dict = lang === "zh" ? ZH : JA;
  return (
    compose(tokenize(nameEn), dict, lang)
    ?? compose(slugTokens(fxPath), dict, lang)
    ?? (lang === "zh" ? nameEn : nameEn)
  );
}

/** Attach zh + ja names to a catalog spell entry. */
export function localizeFxSkill(fxPath, nameEn) {
  const override = FX_OVERRIDES[fxPath];
  const slugName = fxPath.split("/")[1]?.replace(/-/g, " ") ?? "Skill";
  const cleanEn = String(nameEn ?? "").trim() || slugName;
  if (override) {
    return {
      name: override.zh,
      nameEn: cleanEn,
      nameJa: override.ja ?? override.zh,
    };
  }
  return {
    name: translateGeneric(cleanEn, fxPath, "zh"),
    nameEn: cleanEn,
    nameJa: translateGeneric(cleanEn, fxPath, "ja"),
  };
}
